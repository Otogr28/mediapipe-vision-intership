# Adapted from the OpenCV Model Zoo (opencv/opencv_zoo, Apache-2.0):
# models/palm_detection_mediapipe/mp_palmdet.py.
# Only the inference backend is changed: cv.dnn.readNet/forward is replaced
# with an onnxruntime InferenceSession so the model can run on the Jetson's
# CUDA execution provider. All pre/post-processing math (anchors, NMS,
# landmark decoding) is the upstream implementation unchanged. cv2 is still
# used for image ops (resize/copyMakeBorder/NMSBoxes); only the neural-net
# forward pass moved to onnxruntime.
import cv2 as cv
import numpy as np

# onnxruntime is imported lazily inside __init__ so the default MediaPipe
# inference path never requires it to be installed.


class MPPalmDet:
    def __init__(self, modelPath, nmsThreshold=0.3, scoreThreshold=0.5, topK=5000,
                 backendId=0, targetId=0, providers=None):
        import onnxruntime  # lazy: only needed for the GPU/ONNX backend

        self.model_path = modelPath
        self.nms_threshold = nmsThreshold
        self.score_threshold = scoreThreshold
        self.topK = topK
        self.backend_id = backendId
        self.target_id = targetId

        self.input_size = np.array([192, 192]) # wh

        if providers is None:
            providers = ["CUDAExecutionProvider", "CPUExecutionProvider"]
        self.session = onnxruntime.InferenceSession(self.model_path, providers=providers)
        self.input_name = self.session.get_inputs()[0].name
        # Deterministic output order independent of the runtime's internal
        # ordering: sorted names give ["Identity", "Identity_1"], which is the
        # order _postprocess expects: output_blob[0] = box+keypoint deltas
        # [1,2016,18] ("Identity"), output_blob[1] = scores [1,2016,1]
        # ("Identity_1"). Verified against the ONNX file.
        self.output_names = sorted(o.name for o in self.session.get_outputs())

        self.anchors = self._load_anchors()

    @property
    def name(self):
        return self.__class__.__name__

    def setBackendAndTarget(self, backendId, targetId):
        # No-op for the onnxruntime backend: the execution provider is fixed at
        # construction. Kept for API compatibility with the upstream class.
        self.backend_id = backendId
        self.target_id = targetId

    def _preprocess(self, image):
        pad_bias = np.array([0., 0.]) # left, top
        ratio = min(self.input_size / image.shape[:2])
        if image.shape[0] != self.input_size[0] or image.shape[1] != self.input_size[1]:
            # keep aspect ratio when resize
            ratio_size = (np.array(image.shape[:2]) * ratio).astype(np.int32)
            image = cv.resize(image, (ratio_size[1], ratio_size[0]))
            pad_h = self.input_size[0] - ratio_size[0]
            pad_w = self.input_size[1] - ratio_size[1]
            pad_bias[0] = left = pad_w // 2
            pad_bias[1] = top = pad_h // 2
            right = pad_w - left
            bottom = pad_h - top
            image = cv.copyMakeBorder(image, top, bottom, left, right, cv.BORDER_CONSTANT, None, (0, 0, 0))
        image = cv.cvtColor(image, cv.COLOR_BGR2RGB)
        image = image.astype(np.float32) / 255.0 # norm
        pad_bias = (pad_bias / ratio).astype(np.int32)
        return image[np.newaxis, :, :, :], pad_bias # hwc -> nhwc

    def infer(self, image):
        h, w, _ = image.shape

        # Preprocess
        input_blob, pad_bias = self._preprocess(image)

        # Forward (onnxruntime needs a contiguous float32 NHWC tensor; the
        # preprocess already yields NHWC float, this just guarantees dtype +
        # memory layout). output_blob is a list of numpy arrays in
        # self.output_names order, so _postprocess is unchanged.
        input_blob = np.ascontiguousarray(input_blob, dtype=np.float32)
        output_blob = self.session.run(self.output_names, {self.input_name: input_blob})

        # Postprocess
        results = self._postprocess(output_blob, np.array([w, h]), pad_bias)

        return results

    def _postprocess(self, output_blob, original_shape, pad_bias):
        score = output_blob[1][0, :, 0]
        box_delta = output_blob[0][0, :, 0:4]
        landmark_delta = output_blob[0][0, :, 4:]
        scale = max(original_shape)

        # get scores
        score = score.astype(np.float64)
        score = 1 / (1 + np.exp(-score))

        # get boxes
        cxy_delta = box_delta[:, :2] / self.input_size
        wh_delta = box_delta[:, 2:] / self.input_size
        xy1 = (cxy_delta - wh_delta / 2 + self.anchors) * scale
        xy2 = (cxy_delta + wh_delta / 2 + self.anchors) * scale
        boxes = np.concatenate([xy1, xy2], axis=1)
        boxes -= [pad_bias[0], pad_bias[1], pad_bias[0], pad_bias[1]]
        # NMS
        keep_idx = cv.dnn.NMSBoxes(boxes, score, self.score_threshold, self.nms_threshold, top_k=self.topK)
        if len(keep_idx) == 0:
            return np.empty(shape=(0, 19))
        selected_score = score[keep_idx]
        selected_box = boxes[keep_idx]

        # get landmarks
        selected_landmarks = landmark_delta[keep_idx].reshape(-1, 7, 2)
        selected_landmarks = selected_landmarks / self.input_size
        selected_anchors = self.anchors[keep_idx]
        for idx, landmark in enumerate(selected_landmarks):
            landmark += selected_anchors[idx]
        selected_landmarks *= scale
        selected_landmarks -= pad_bias

        # [
        #   [bbox_coords, landmarks_coords, score]
        #   ...
        #   [bbox_coords, landmarks_coords, score]
        # ]
        return np.c_[selected_box.reshape(-1, 4), selected_landmarks.reshape(-1, 14), selected_score.reshape(-1, 1)]

